// Automatically falls back to English for any key not yet translated in a regional dictionary
const createLangProxy = (langDict) =>
  new Proxy(langDict, {
    get(target, prop) {
      if (typeof prop === 'string' && prop in target) {
        return target[prop];
      }
      return RAW_TRANSLATIONS.en[prop];
    },
  });

export const translations = Object.fromEntries(
  Object.entries(RAW_TRANSLATIONS).map(([code, dict]) => [
    code,
    code === 'en' ? dict : createLangProxy(dict),
  ])
);
