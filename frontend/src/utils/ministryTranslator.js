export function translateMinistry(rawMinistry, lang = "en") {
  if (!rawMinistry || lang === "en") return rawMinistry
  const clean = String(rawMinistry).trim()
  if (MINISTRIES[clean] && MINISTRIES[clean][lang]) {
    return MINISTRIES[clean][lang]
  }

  // Substring matching for variations
  for (const [key, map] of Object.entries(MINISTRIES)) {
    if (clean.toLowerCase().includes(key.toLowerCase()) || key.toLowerCase().includes(clean.toLowerCase())) {
      if (map[lang]) return map[lang]
    }
  }

  return rawMinistry
}

export function translateApplicationMode(rawMode, lang = "en") {
  if (!rawMode || lang === "en") return rawMode
  const clean = String(rawMode).trim().toUpperCase()
  if (MODES[clean] && MODES[clean][lang]) {
    return MODES[clean][lang]
  }
  return rawMode
}
