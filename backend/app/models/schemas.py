"""Civic_AI Pydantic v2 Schemas for API Requests and Responses."""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


# --- Shared / Base ---
class BaseSchema(BaseModel):
    """Base schema for Civic_AI with standard Pydantic v2 configuration."""
    model_config = {"from_attributes": True}


# --- Explain Feature (Section 3.1) ---
class ExplainRequest(BaseModel):
    """Request payload for /api/explain."""
    text: Optional[str] = Field(default=None, description="Raw notice or document text")
    document_url: Optional[str] = Field(default=None, description="URL to the document")
    document_type: Optional[str] = Field(default=None, description="Detected or indicated document type")
    state: Optional[str] = Field(default=None, description="State/UT code or Central")
    lang: str = Field(default="en", description="Target language code (MVP defaults to 'en')")


class ExplainResponse(BaseSchema):
    """Structured response output for notice explainer."""
    plain_summary: str = Field(..., description="Summary in max 120 words at Grade 6 reading level")
    who_is_affected: str = Field(..., description="Citizen groups affected by this notice")
    key_points: List[str] = Field(default_factory=list, description="Primary takeaways")
    deadlines: List[str] = Field(default_factory=list, description="Critical dates and deadlines in ISO format")
    required_documents: List[str] = Field(default_factory=list, description="Documents required from citizen")
    actions_for_citizen: List[str] = Field(default_factory=list, description="Clear actionable next steps")
    risk_flags: List[str] = Field(default_factory=list, description="Penalties, lapses, or pitfalls")
    jargon_glossary: List[Dict[str, str]] = Field(default_factory=list, description="Plain definitions of legal/bureaucratic terms")
    source_url: Optional[str] = Field(default=None, description="Official source URL")
    last_verified: Optional[datetime] = Field(default=None, description="Verification timestamp")
    lang: str = Field(default="en", description="Language of the explanation")


# --- Eligibility Feature (Section 3.2) ---
class CitizenProfile(BaseModel):
    """Citizen demographic and socioeconomic attributes for eligibility determination."""
    age: Optional[int] = None
    gender: Optional[str] = None
    state: Optional[str] = None
    annual_income: Optional[float] = None
    category: Optional[str] = None  # farmer, student, woman, senior, disabled, worker, entrepreneur
    caste_category: Optional[str] = None  # General, OBC, SC, ST
    occupation: Optional[str] = None
    residence: Optional[str] = None  # rural, urban
    land_holding_acres: Optional[float] = None
    disability_percentage: Optional[float] = None
    extra_attributes: Dict[str, Any] = Field(default_factory=dict)


class EligibilityRequest(BaseModel):
    """Request payload for /api/eligibility."""
    profile: CitizenProfile = Field(..., description="User attributes for eligibility checking")
    state: Optional[str] = Field(default=None, description="State/UT code, or Central")
    scheme_category: Optional[str] = Field(default=None, description="Filter category")
    lang: str = Field(default="en", description="Language code")


class StateApplyLink(BaseModel):
    """Direct application link for state-specific or integrated portals."""
    state: str = Field(..., description="Target State/UT name or code")
    portal_name: str = Field(..., description="Name of the official state application portal")
    url: str = Field(..., description="Direct URL to apply")


class OfficialSourceLink(BaseModel):
    """Verified official government source reference."""
    title: str = Field(..., description="Source title or notification reference")
    url: str = Field(..., description="Official government URL")


class SchemeMatchResult(BaseSchema):
    """Deterministic eligibility outcome for an individual scheme."""
    scheme_id: str
    scheme_name: str
    status: str = Field(..., description="'eligible' | 'not_eligible' | 'need_more_info'")
    deciding_rule: str = Field(..., description="The exact deterministic rule that decided eligibility")
    explanation: str = Field(..., description="Human-friendly explanation generated by Civic_AI")
    scheme_type: str = Field(default="central", description="'central' | 'state' | 'integrated' | 'multi_state' | 'local'")
    applicable_states: List[str] = Field(default_factory=lambda: ["All India"], description="List of applicable states or ['All India']")
    nodal_authority: str = Field(default="", description="Nodal Ministry or State Department")
    application_mode: str = Field(default="online", description="'online' | 'offline' | 'hybrid'")
    direct_apply_url: Optional[str] = Field(default=None, description="Direct URL to official application portal")
    state_apply_links: List[Dict[str, str]] = Field(default_factory=list, description="State-by-state application portals")
    official_source_links: List[Dict[str, str]] = Field(default_factory=list, description="Official government references")
    benefits: List[str] = Field(default_factory=list)
    documents_needed: List[str] = Field(default_factory=list)
    how_to_apply: str = ""
    official_link: str = ""
    last_verified: Optional[datetime] = None


class SchemeDetail(BaseSchema):
    """Complete structured public welfare scheme specification."""
    scheme_id: str
    scheme_name: str
    scheme_type: str = Field(default="central", description="'central' | 'state' | 'integrated' | 'multi_state' | 'local'")
    applicable_states: List[str] = Field(default_factory=lambda: ["All India"])
    state: str = Field(default="Central")
    nodal_authority: str = Field(default="")
    ministry: str = Field(default="")
    category: str = Field(default="social_welfare")
    benefit_type: str = Field(default="Cash / DBT")
    summary: str = Field(default="")
    benefits: List[str] = Field(default_factory=list)
    eligibility_criteria: List[str] = Field(default_factory=list)
    exclusions: List[str] = Field(default_factory=list)
    documents_needed: List[str] = Field(default_factory=list)
    application_mode: str = Field(default="online", description="'online' | 'offline' | 'hybrid'")
    how_to_apply: str = Field(default="")
    direct_apply_url: Optional[str] = Field(default=None)
    state_apply_links: List[StateApplyLink] = Field(default_factory=list)
    official_link: str = Field(default="")
    myscheme_link: Optional[str] = Field(default=None)
    official_source_links: List[OfficialSourceLink] = Field(default_factory=list)
    rules: Dict[str, Any] = Field(default_factory=dict)
    is_live_verified: bool = Field(default=False)
    live_timestamp: Optional[str] = None


class EligibilityResponse(BaseSchema):
    """Aggregate schemes eligibility response."""
    results: List[SchemeMatchResult] = Field(default_factory=list)
    follow_up_questions: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Follow-up adaptive questions if 'need_more_info' is triggered"
    )
    lang: str = Field(default="en")


# --- Rights Feature (Section 3.3) ---
class RightsRequest(BaseModel):
    """Request payload for /api/rights."""
    question: str = Field(..., description="Citizen legal query")
    state: Optional[str] = Field(default=None, description="State/UT code or Central")
    lang: str = Field(default="en", description="Language code")


class Citation(BaseModel):
    """Mandatory citation to official legal act or section."""
    act_name: str
    section: str
    url: str


class RightsResponse(BaseSchema):
    """Structured response for rights and local law inquiries."""
    question: str
    your_rights: List[str] = Field(default_factory=list)
    what_you_can_do: List[str] = Field(default_factory=list)
    where_to_complain_or_get_free_help: List[str] = Field(default_factory=list)
    citations: List[Citation] = Field(default_factory=list)
    has_official_source: bool = True
    disclaimer: str = (
        "This information is for informational purposes only and does not constitute "
        "formal legal advice. Always consult a qualified legal professional or free legal aid (NALSA)."
    )
    lang: str = Field(default="en")


# --- Verification Feature (Section 3.5) ---
class VerifyRequest(BaseModel):
    """Request payload for /api/verify."""
    claim_or_circular_title: str
    source_url: Optional[str] = None
    state: Optional[str] = None
    stated_deadline: Optional[str] = None
    lang: str = Field(default="en", description="Language code")


class VerifyResponse(BaseSchema):
    """Live verification result badge and details."""
    badge: str = Field(
        ...,
        description="'Verified today' | 'Possibly outdated: newer circular found' | 'Could not verify'"
    )
    source_url: Optional[str] = None
    last_verified: datetime
    newer_circular_title: Optional[str] = None
    newer_circular_url: Optional[str] = None
    notes: Optional[str] = None
    lang: str = "en"


# --- State Registry Coverage (Section 4.3) ---
class StateCoverageItem(BaseSchema):
    """Coverage and freshness metrics for a State/UT."""
    code: str
    name: str
    tier: int
    rules_extracted_count: int = 0
    acts_indexed_count: int = 0
    last_refreshed: Optional[datetime] = None
    status: str = "unverified"
    official_portal: Optional[str] = None


class StatesResponse(BaseSchema):
    """Response payload for /api/states."""
    states: List[StateCoverageItem]
    pilot_states: List[str]
    total_states: int
    lang: str = "en"
